export function getLocaleFromCookieHeader(value: string | undefined): Locale {
  return /(?:^|;\s*)locale=en(?:;|$)/.test(value ?? '') ? 'en' : 'de';
}

function interpolate(value: string, variables?: Record<string, string | number>): string {
  if (!variables) return value;
  return value.replace(/\{(\w+)\}/g, (_, key: string) => String(variables[key] ?? `{${key}}`));
}

export function translate(locale: Locale, key: string, variables?: Record<string, string | number>): string {
  return interpolate(messages[locale][key] ?? messages.de[key] ?? key, variables);
}

interface I18nContextValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: string, variables?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children, initialLocale = 'de' }: { children: ReactNode; initialLocale?: Locale }) {
  const router = useRouter();
  const [locale, setLocaleState] = useState<Locale>(initialLocale);

  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);

  function setLocale(nextLocale: Locale) {
    setLocaleState(nextLocale);
    document.cookie = `locale=${nextLocale}; Path=/; Max-Age=31536000; SameSite=Lax`;
    document.documentElement.lang = nextLocale;
    router.refresh();
  }

  const value = useMemo(() => ({ locale, setLocale, t: (key: string, variables?: Record<string, string | number>) => translate(locale, key, variables) }), [locale]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const context = useContext(I18nContext);
  if (!context) throw new Error('useI18n must be used inside I18nProvider');
  return context;
}

export function translateApiError(locale: Locale, code: string | undefined, fallback: string): string {
  const key = code ? `error.${code}` : '';
  const value = key ? translate(locale, key) : key;
  return value === key ? fallback : value;
}

export function getApiErrorMessage(
  locale: Locale,
  payload: { code?: string; error?: string; message?: string },
  fallback: string,
): string {
  return translateApiError(locale, payload.code, payload.error ?? payload.message ?? fallback);
}
